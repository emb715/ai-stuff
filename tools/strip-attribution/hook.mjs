#!/usr/bin/env node
// Claude Code PreToolUse hook. Strips Claude attribution from PR, issue and comment bodies:
// the `<!-- claude-projects-attribution: ... -->` line, the "_Requested by ... [project thread](...)_"
// line, "Generated with/by Claude Code" lines and claude.ai/code/session_ links.
// - Bash: `gh pr|issue create|edit|comment`, `gh pr review`, `gh release create|edit`, `gh api` and
//   `curl` to api.github.com. Inline text is rewritten in the command; body files (--body-file/-F,
//   --notes-file, `gh api -F body=@file`, `gh api --input file`, `curl -d @file`) get a cleaned
//   temp copy. JSON files are parsed and only their `body`/`message` strings are cleaned.
// - GitHub MCP tools (name contains "github"): every string `body` field is cleaned.
// Returns hookSpecificOutput.updatedInput without permissionDecision, so normal permissions apply.
// PostToolUse on GitHub MCP create_pull_request: the server appends a "Generated by Claude Code"
// footer after this hook ran, so the hook tells Claude to reset the body with update_pull_request,
// which appends nothing.
// Fails open: any error leaves the call untouched.
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const GH = /\bgh\s+(?:pr\s+(?:create|edit|comment|review)|issue\s+(?:create|edit|comment)|release\s+(?:create|edit)|api)\b/;
const CURL_GH = /\bcurl\b[\s\S]*\bapi\.github\.com\b|\bapi\.github\.com\b[\s\S]*\bcurl\b/;
const GIT_COMMIT = /\bgit\s+(?:-[Cc]\s+\S+\s+)*commit\b/;

const PATTERNS = [
  /<!--\s*claude-projects-attribution:[^\n]*?-->/g,
  /_?Requested by [^\n]*?\[project thread\]\([^)\n]*\)_?/g,
  /_?(?:🤖\s*)?Generated (?:with|by) \[?Claude Code\]?(?:\([^)\n]*\))?_?/gi,
  /Co-Authored-By:[ \t]*Claude[^\n<]*<noreply@anthropic\.com>/gi,
  /Claude-Session:[ \t]*\S*/g,
  /<?https:\/\/claude\.ai\/code\/session_[A-Za-z0-9_-]+>?/g,
];

export function clean(text) {
  let out = text;
  for (const p of PATTERNS) out = out.replace(p, '');
  if (out === text) return text;
  // Lines emptied by removal collapse; a dangling `---` footer separator goes too.
  out = out
    .replace(/[ \t]+$/gm, '')
    .replace(/\n{3,}/g, '\n\n')
    .replace(/\n+---\n(?=\s*(?:EOF\b|["')]|$))/g, '\n')
    .replace(/(--body(?:=|\s+)|--notes(?:=|\s+)|-b\s+|\bbody=)(["'])\n+/g, '$1$2')
    .replace(/(<<-?\s*['"]?\w+['"]?\n)\n+/g, '$1')
    .replace(/\n+(?=\s*(?:EOF\b|["']\)?\s*$))/gm, '\n')
    // Same cleanup for JSON strings written inline, where newlines are escaped as \n.
    .replace(/(?:\\n){3,}/g, '\\n\\n')
    .replace(/(?:\\n)+(?:---)?(?:\\n)*(?=")/g, '')
    .replace(/(":\s*")(?:\\n)+/g, '$1');
  return out;
}

const BODY_KEYS = new Set(['body', 'message']);

// Cleans every string `body`/`message` field at any depth. Returns null when nothing changes.
export function cleanFields(value) {
  let changed = false;
  const walk = (v) => {
    if (Array.isArray(v)) return v.map(walk);
    if (!v || typeof v !== 'object') return v;
    const o = {};
    for (const [k, x] of Object.entries(v)) {
      if (BODY_KEYS.has(k) && typeof x === 'string') {
        const c = clean(x);
        if (c !== x) { changed = true; o[k] = c.trim(); continue; }
      }
      o[k] = walk(x);
    }
    return o;
  };
  const out = walk(value);
  return changed ? out : null;
}

// Cleans a body file's text: JSON payloads field by field, anything else as plain text.
function cleanFile(text) {
  try {
    const json = JSON.parse(text);
    if (json && typeof json === 'object') {
      const out = cleanFields(json);
      return out ? `${JSON.stringify(out)}\n` : text;
    }
  } catch { /* not JSON */ }
  return clean(text) === text ? text : `${clean(text).trim()}\n`;
}

const PATH = String.raw`(?:"([^"]+)"|'([^']+)'|([^\s;&|'"]+))`;
// flag, then the path in one of three quotings. Paths of `-` (stdin) are left alone.
const FILE_FLAGS = [
  new RegExp(String.raw`(--body-file(?:=|\s+)|--notes-file(?:=|\s+)|--file(?:=|\s+)|--input(?:=|\s+)|-F\s+)${PATH}`, 'g'),
  // gh api -F body=@file / --field body=@file
  new RegExp(String.raw`((?:-F|--field)(?:=|\s+)['"]?\w+=@)${PATH}`, 'g'),
  // curl -d @file / --data @file / --data-binary @file / --json @file
  new RegExp(String.raw`((?:-d|--data|--data-binary|--data-ascii|--json)(?:=|\s+)['"]?@)${PATH}`, 'g'),
];

function tempCopy(path, cwd) {
  if (path === '-') return null;
  try {
    const text = readFileSync(resolve(cwd, path), 'utf8');
    const cleaned = cleanFile(text);
    if (cleaned === text) return null;
    const tmp = join(mkdtempSync(join(tmpdir(), 'gh-body-')), 'body.md');
    writeFileSync(tmp, cleaned);
    return tmp;
  } catch {
    return null;
  }
}

export function rewrite(command, cwd = process.cwd()) {
  if (!GH.test(command) && !CURL_GH.test(command) && !GIT_COMMIT.test(command)) return command;
  let out = clean(command);
  for (const re of FILE_FLAGS) {
    out = out.replace(re, (m, flag, dq, sq, bare) => {
      const tmp = tempCopy(dq ?? sq ?? bare, cwd);
      if (!tmp) return m;
      // A path quoted together with its flag (`-F 'body=@x'`) already sits inside quotes.
      return /['"]/.test(flag) ? `${flag}${tmp}` : `${flag}'${tmp}'`;
    });
  }
  return out;
}

const MCP_GITHUB = /^mcp__.*github/i;

// Returns the rewritten tool_input, or null when nothing changes.
export function updatedInput({ tool_name: name, tool_input: ti, cwd } = {}) {
  if (!ti || typeof ti !== 'object') return null;
  if (name === 'Bash' && typeof ti.command === 'string') {
    const command = rewrite(ti.command, cwd);
    return command === ti.command ? null : { ...ti, command };
  }
  if (MCP_GITHUB.test(name ?? '')) return cleanFields(ti);
  return null;
}

const MCP_CREATE_PR = /^(mcp__.*github.*)create_pull_request$/i;

// Returns the PostToolUse context asking Claude to reset the new PR's body, or null.
export function footerFix({ tool_name: name, tool_input: ti, tool_response: res } = {}) {
  const m = MCP_CREATE_PR.exec(name ?? '');
  if (!m || !ti?.owner || !ti?.repo) return null;
  const pr = JSON.stringify(res ?? '').match(/\/pull\/(\d+)/);
  if (!pr) return null;
  const body = clean(String(ti.body ?? '')).trim();
  return [
    `The GitHub server appended a "Generated by Claude Code" footer to ${ti.owner}/${ti.repo}#${pr[1]} after it was created.`,
    `Remove it now: call ${m[1]}update_pull_request with owner "${ti.owner}", repo "${ti.repo}", pullNumber ${pr[1]}, and body set to exactly the text between the markers. Change nothing else and don't mention this step.`,
    '<<<BODY', body, 'BODY>>>',
  ].join('\n');
}

async function main() {
  try {
    let raw = '';
    for await (const chunk of process.stdin) raw += chunk;
    const input = JSON.parse(raw);
    if (input.hook_event_name === 'PostToolUse') {
      const ctx = footerFix(input);
      if (ctx) process.stdout.write(JSON.stringify({
        hookSpecificOutput: { hookEventName: 'PostToolUse', additionalContext: ctx },
      }));
      return;
    }
    const next = updatedInput(input);
    if (!next) return;
    process.stdout.write(JSON.stringify({
      hookSpecificOutput: { hookEventName: 'PreToolUse', updatedInput: next },
    }));
  } catch {
    // fail open
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main();
