import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { rewrite, updatedInput, footerFix } from '../hook.mjs';

const HOOK = new URL('../hook.mjs', import.meta.url).pathname;
const ATTR = '<!-- claude-projects-attribution: {"github_login":"x"} -->\n_Requested by **X** · [project thread](https://claude.ai/code/project/c?thread=t)_\n\n';
const FOOT = '\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nhttps://claude.ai/code/session_abc123\n';
const LEAK = /claude-projects-attribution|Requested by|Generated (with|by)|code\/session_/i;

const run = (command) => {
  const r = spawnSync('node', [HOOK], { input: JSON.stringify({ tool_name: 'Bash', cwd: '/', tool_input: { command } }) });
  return r.stdout.toString();
};

test('heredoc PR body loses attribution and footer, keeps content', () => {
  const out = rewrite(`gh pr create --title t --body "$(cat <<'EOF'\n${ATTR}## Summary\n- x${FOOT}EOF\n)"`);
  assert.doesNotMatch(out, LEAK);
  assert.match(out, /<<'EOF'\n## Summary\n- x\nEOF\n\)"$/);
});

test('comment footer and dangling separator removed', () => {
  const out = rewrite('gh pr comment 1 --body "Done.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"');
  assert.doesNotMatch(out, LEAK);
  assert.doesNotMatch(out, /---/);
  assert.match(out, /Done\./);
});

test('--body-file is cleaned into a temp copy, original untouched', () => {
  const dir = mkdtempSync(join(tmpdir(), 'hook-test-'));
  const file = join(dir, 'b.md');
  writeFileSync(file, `${ATTR}Body${FOOT}`);
  const out = rewrite(`gh issue comment 2 --body-file ${file}`);
  const tmp = out.match(/--body-file '([^']+)'/)[1];
  assert.equal(readFileSync(tmp, 'utf8'), 'Body\n');
  assert.match(readFileSync(file, 'utf8'), LEAK);
});

test('non-gh-body commands are untouched', () => {
  for (const c of ['echo "Generated with Claude Code"', 'gh pr list', 'git log --grep "Generated with Claude Code"']) {
    assert.equal(rewrite(c), c);
  }
});

test('hook emits updatedInput without permissionDecision, silent when unchanged', () => {
  const o = JSON.parse(run(`gh pr edit 1 --body "${ATTR}hi"`)).hookSpecificOutput;
  assert.equal(o.hookEventName, 'PreToolUse');
  assert.equal(o.permissionDecision, undefined);
  assert.doesNotMatch(o.updatedInput.command, LEAK);
  assert.equal(run('gh pr list'), '');
});

test('GitHub MCP tools: body cleaned, other fields kept', () => {
  const out = updatedInput({ tool_name: 'mcp__github__create_pull_request', tool_input: { title: 'Generated with Claude Code', body: `${ATTR}## Summary${FOOT}` } });
  assert.deepEqual(out, { title: 'Generated with Claude Code', body: '## Summary' });
});

test('GitHub MCP tools: nested review comment bodies cleaned', () => {
  const out = updatedInput({ tool_name: 'mcp__plugin_github_github__pull_request_review_write', tool_input: { comments: [{ path: 'a', body: 'Fix.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_' }] } });
  assert.deepEqual(out, { comments: [{ path: 'a', body: 'Fix.' }] });
});

test('MCP: clean body or non-GitHub server returns null', () => {
  assert.equal(updatedInput({ tool_name: 'mcp__github__add_issue_comment', tool_input: { body: 'clean' } }), null);
  assert.equal(updatedInput({ tool_name: 'mcp__slack__send', tool_input: { body: ATTR } }), null);
});

test('hook process: MCP call emits updatedInput', () => {
  const r = spawnSync('node', [HOOK], { input: JSON.stringify({ tool_name: 'mcp__github__add_issue_comment', tool_input: { issue_number: 1, body: `${ATTR}hi` } }) });
  assert.deepEqual(JSON.parse(r.stdout).hookSpecificOutput.updatedInput, { issue_number: 1, body: 'hi' });
});
const TRAILERS = '\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>\nClaude-Session: ';

test('git commit heredoc: Claude trailers removed, message kept', () => {
  const out = rewrite(`git commit -m "$(cat <<'EOF'\nfeat(x): add y\n\nBody.${TRAILERS}\nEOF\n)"`);
  assert.doesNotMatch(out, /Co-Authored-By|Claude-Session/i);
  assert.match(out, /<<'EOF'\nfeat\(x\): add y\n\nBody\.\nEOF\n\)"$/);
});

test('git commit -F file: cleaned temp copy; -C prefix recognised', () => {
  const dir = mkdtempSync(join(tmpdir(), 'hook-test-'));
  const file = join(dir, 'msg.txt');
  writeFileSync(file, `fix: z${TRAILERS}\n`);
  const out = rewrite(`git -C repo commit -F ${file}`);
  assert.equal(readFileSync(out.match(/-F '([^']+)'/)[1], 'utf8'), 'fix: z\n');
});

test('human co-authors and non-commit git commands untouched', () => {
  const keep = 'git commit -m "fix: a\n\nCo-Authored-By: Jane <jane@example.com>"';
  assert.equal(rewrite(keep), keep);
  const log = 'git log --grep "Co-Authored-By: Claude <noreply@anthropic.com>"';
  assert.equal(rewrite(log), log);
});

test('GitHub MCP commit message field cleaned', () => {
  const out = updatedInput({ tool_name: 'mcp__github__push_files', tool_input: { branch: 'b', message: `feat: x${TRAILERS}` } });
  assert.deepEqual(out, { branch: 'b', message: 'feat: x' });
});

const created = (extra = {}) => ({
  hook_event_name: 'PostToolUse',
  tool_name: 'mcp__github__create_pull_request',
  tool_input: { owner: 'o', repo: 'r', title: 't', head: 'h', base: 'main', body: `${ATTR}Body${FOOT}` },
  tool_response: [{ type: 'text', text: '{"id":"1","url":"https://github.com/o/r/pull/7"}' }],
  ...extra,
});

test('PostToolUse create_pull_request asks for an update with the cleaned body', () => {
  const ctx = footerFix(created());
  assert.match(ctx, /call mcp__github__update_pull_request with owner "o", repo "r", pullNumber 7/);
  assert.match(ctx, /<<<BODY\nBody\nBODY>>>/);
  assert.doesNotMatch(ctx.split('<<<BODY')[1], LEAK);
});

test('PostToolUse keeps plugin-scoped tool prefix and accepts a string response', () => {
  const ctx = footerFix(created({ tool_name: 'mcp__plugin_x_github__create_pull_request', tool_response: 'https://github.com/o/r/pull/12' }));
  assert.match(ctx, /mcp__plugin_x_github__update_pull_request .*pullNumber 12/);
});

test('PostToolUse ignores other tools and responses without a PR number', () => {
  assert.equal(footerFix(created({ tool_name: 'mcp__github__update_pull_request' })), null);
  assert.equal(footerFix(created({ tool_response: 'error: validation failed' })), null);
  assert.equal(footerFix(created({ tool_input: { body: 'x' } })), null);
});

test('PostToolUse output is additionalContext, never updatedInput', () => {
  const r = spawnSync('node', [HOOK], { input: JSON.stringify(created()) });
  const out = JSON.parse(r.stdout.toString()).hookSpecificOutput;
  assert.equal(out.hookEventName, 'PostToolUse');
  assert.match(out.additionalContext, /pullNumber 7/);
  assert.equal(out.updatedInput, undefined);
});
