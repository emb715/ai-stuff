/**
 * init command — scaffolds the boundary pattern on a repo.
 *
 * Dry-run (default): reports what would be created, extracted surface, would-pass/fail.
 * Write: creates AGENTS.md templates, decisions/ dirs, and docs/boundaries.md.
 *
 * Reads: boundaries.yaml manifest.
 * Does NOT: write obligation content, decide boundaries, create ADRs.
 */

import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { Manifest, BoundaryEntry } from "./manifest.ts";
import { boundaryDir } from "./manifest.ts";
import { extractSurface, type SurfaceSymbol } from "./surface.ts";
import { parseAGENTS } from "./markdown.ts";
import { generateAgentsTemplate } from "./template.ts";
import { checkBoundary } from "./check.ts";

export interface InitBoundaryReport {
  name: string;
  dir: string;
  agentsMdExists: boolean;
  surface: {
    entryFiles: string[];
    extractedSymbols: string[];
    surfaceSymbols: SurfaceSymbol[];
    emptyFiles: string[];
    missingFiles: string[];
  };
  wouldCreate: string[];
  wouldPass: boolean;
  checkResult: import("./check.ts").BoundaryCheckResult | null;
}

export interface InitReport {
  manifest: Manifest;
  boundaries: InitBoundaryReport[];
  mapContents: string;
}

/**
 * Run init in dry-run mode. Reports what would be created and whether
 * the would-be contracts would pass check.
 */
export function initDryRun(manifest: Manifest): InitReport {
  const boundaries: InitBoundaryReport[] = [];

  for (const entry of manifest.boundaries) {
    boundaries.push(analyzeBoundary(manifest, entry));
  }

  const mapContents = generateMapContents(manifest, boundaries);

  return { manifest, boundaries, mapContents };
}

/**
 * Run init in write mode. Creates files. Skips existing AGENTS.md (idempotent).
 */
export function initWrite(manifest: Manifest): InitReport {
  const report = initDryRun(manifest);

  for (let i = 0; i < manifest.boundaries.length; i++) {
    const entry = manifest.boundaries[i];
    const bReport = report.boundaries[i];
    const bDir = boundaryDir(manifest, entry);

    // Create decisions/ dir
    const decisionsDir = join(bDir, "decisions");
    if (!existsSync(decisionsDir)) {
      mkdirSync(decisionsDir, { recursive: true });
    }

    // Create AGENTS.md only if it doesn't exist (idempotent)
    const agentsPath = join(bDir, "AGENTS.md");
    if (!existsSync(agentsPath)) {
      writeFileSync(
        agentsPath,
        generateAgentsTemplate(entry, bReport.surface.surfaceSymbols),
        "utf-8",
      );
    }

    // Log what was created
    if (!bReport.agentsMdExists) {
      bReport.wouldCreate.push(`${agentsPath} (created)`);
    }
    bReport.wouldCreate.push(`${decisionsDir} (created)`);
  }

  // Create docs/boundaries.md
  const docsDir = join(manifest.repoRoot, "docs");
  if (!existsSync(docsDir)) {
    mkdirSync(docsDir, { recursive: true });
  }
  const mapPath = join(docsDir, "boundaries.md");
  writeFileSync(mapPath, report.mapContents, "utf-8");

  return report;
}

/**
 * Analyze a single boundary for the init report.
 */
function analyzeBoundary(manifest: Manifest, entry: BoundaryEntry): InitBoundaryReport {
  const bDir = boundaryDir(manifest, entry);
  const agentsPath = join(bDir, "AGENTS.md");
  const agentsMdExists = existsSync(agentsPath);

  // Extract surface from entry files
  const surface = extractSurface(bDir, entry.surface);

  const wouldCreate: string[] = [];
  if (!agentsMdExists) {
    wouldCreate.push(`AGENTS.md (template — fill with obligations)`);
  }
  wouldCreate.push(`decisions/ (empty — ADRs only on real decisions)`);

  // Run check against existing AGENTS.md if it exists
  const checkResult = checkBoundary(manifest, entry);

  return {
    name: entry.name,
    dir: bDir,
    agentsMdExists,
    surface: {
      entryFiles: surface.entryFiles,
      extractedSymbols: surface.symbols.map((s) => s.name),
      surfaceSymbols: surface.symbols,
      emptyFiles: surface.emptyFiles,
      missingFiles: surface.missingFiles,
    },
    wouldCreate,
    wouldPass: checkResult.passed,
    checkResult,
  };
}

/**
 * Generate the contents of docs/boundaries.md (YAML frontmatter + table).
 *
 * The map is derived from per-boundary AGENTS.md files (single source of truth).
 * If AGENTS.md doesn't exist yet, falls back to the manifest's purpose.
 */
export function generateMapContents(
  manifest: Manifest,
  boundaries: InitBoundaryReport[],
): string {
  const lines: string[] = [];

  lines.push("<!-- Generated by `boundary map`. Do not edit — regenerate with 'boundary map'. -->");
  lines.push("");
  lines.push("---");
  lines.push(`generated: ${new Date().toISOString()}`);
  lines.push(`maxLines: ${manifest.maxLines}`);
  lines.push(`boundaryCount: ${boundaries.length}`);
  lines.push("---");
  lines.push("");
  lines.push("# Boundary Map");
  lines.push("");
  lines.push("| Boundary | Purpose | Dir | Surface symbols | AGENTS.md |");
  lines.push("|---|---|---|---|---|");

  for (let i = 0; i < manifest.boundaries.length; i++) {
    const entry = manifest.boundaries[i];
    const bReport = boundaries[i];

    // Read purpose from AGENTS.md if it exists (single source of truth).
    // Fall back to manifest purpose if no AGENTS.md yet.
    let purpose = entry.purpose;
    if (bReport.agentsMdExists) {
      const parsed = parseAGENTS(join(bReport.dir, "AGENTS.md"));
      if (parsed?.purpose) {
        purpose = parsed.purpose;
      }
    }

    const symbolCount = bReport.surface.extractedSymbols.length;
    const agentsStatus = bReport.agentsMdExists ? "exists" : "not created";
    lines.push(
      `| ${entry.name} | ${purpose} | ${entry.dir} | ${symbolCount} | ${agentsStatus} |`,
    );
  }

  lines.push("");
  return lines.join("\n");
}